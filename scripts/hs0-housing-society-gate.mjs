import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const checks=[]; const ok=(name,cond)=>checks.push([name,!!cond]);
const contracts=read('core/verticals/contracts.ts');
const registry=read('app-shell/vertical-registry.ts');
const runtime=read('app-shell/vertical-runtime.ts');
const caps=read('app-shell/vertical-capabilities.ts');
const config=read('templates/productized/config.ts');
const template=read('templates/housing-society/definition.ts');
const composition=read('verticals/housing-society/runtime/composition.ts');
const setup=read('components/SetupScreen.tsx');
const app=read('components/TemplateNetworkApp.tsx');
const migration=read('supabase/migrations/082_hs0_housing_society_vertical.sql');
const css=read('app/globals.css');
const guide=read('lib/user-guide-content.ts');
const networksHome=read('components/MyNetworksHome.tsx');
const switcher=read('components/shared/NetworkSwitcher.tsx');
const launchConsole=read('components/FounderLaunchConsole.tsx');
ok('typed vertical kind',contracts.includes('"housing-society"'));
ok('domain capability declared',contracts.includes('"domain.housing-society"'));
ok('registry and runtime registered',registry.includes('HOUSING_SOCIETY_VERTICAL')&&runtime.includes('HOUSING_SOCIETY_APP_COMPOSITION'));
ok('capability runtime fails closed as productized template',caps.includes('"housing-society": {mode:"productized-template"'));
ok('unit is primary operating entity',template.includes('primaryEntityKind:"unit"'));
ok('property dimensions include building wing floor',template.includes('key:"building"')&&template.includes('key:"wing"')&&template.includes('key:"floor"'));
ok('ownership and occupancy semantics explicit',template.includes('owned_by')&&template.includes('tenanted_by')&&template.includes('resident_of')&&template.includes('member_of_household'));
ok('setup exposes create and playground',setup.includes('"housing-society"'));
ok('productized config has synthetic society',config.includes('Green Meadows Housing Society')&&config.includes('housingUnits')&&config.includes('housingPeople'));
ok('resident UX hides platform intelligence',!composition.includes('find("intelligence")'));
ok('resident directory includes unit household person',app.includes('kind==="housing-society"?entities.filter(e=>e.entity.kind==="unit"||e.entity.kind==="household"||e.entity.kind==="person")'));
ok('distinct civic theme',css.includes('.housing-society-network')&&css.includes('--product:#176b72'));
ok('guide truth distinguishes current vs future',guide.includes('housing-society-home')&&guide.includes('housing-society-roadmap')&&guide.includes('status:"future"'));
ok('rerun-safe constraints',migration.includes('drop constraint if exists')&&migration.includes('on conflict(feature_key) do update'));
ok('database productized contract includes housing',migration.includes("select p_kind in ('association','family-association','housing-society'"));
ok('database allowed entities include unit household person',migration.includes("when 'housing-society' then p_entity_kind in ('unit','household','person'"));
ok('database relationship contract includes ownership tenancy occupancy',migration.includes("when 'housing-society' then p_rel in ('owned_by','co_owned_by','occupied_by','tenanted_by'"));
ok('database hierarchy seeded',migration.includes("'property-hierarchy','Building → Wing → Floor → Unit'"));
ok('launch control recognizes housing',migration.includes("'family-association','housing-society','organization'"));
ok('post-migration assertions included',migration.includes('HS-0 compatibility check failed'));
ok('global network home surfaces housing',networksHome.includes('\"housing-society\":\"Run flats, residents and society participation')&&networksHome.includes('[\"family\",\"housing-society\"'));
ok('network switcher uses society icon',switcher.includes('kind===\"housing-society\"')&&switcher.includes('Building2'));
ok('founder launch control includes housing',launchConsole.includes('[\"family\",\"housing-society\"'));
ok('housing home cannot open hidden generic contribute/outcome surfaces',app.includes('kind!==\"housing-society\"&&<button className=\"btn small\" onClick={()=>setTab(\"contribute\")}')&&app.includes('kind!==\"family-association\"&&<>{kind!==\"housing-society\"&&<><NetworkOutcomeHome'));
for(const [name,pass] of checks) console.log(`${pass?'PASS':'FAIL'} ${name}`);
if(checks.some(([,pass])=>!pass)) process.exit(1);
console.log(`HS-0 source gate passed (${checks.length} checks).`);
