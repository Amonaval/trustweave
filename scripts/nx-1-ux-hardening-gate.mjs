import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const fail=m=>{console.error(`NX-1 UX hardening gate: FAIL — ${m}`);process.exit(1)};
const css=read('app/globals.css');
const app=read('components/NetworkApp.tsx');
const my=read('components/MyNetworksHome.tsx');
const setup=read('components/SetupScreen.tsx');
const product=read('components/TemplateNetworkApp.tsx');
const alumni=read('components/AlumniNetworkApp.tsx');
for(const marker of ['.alpha-entry-options>.playground-gallery','.alpha-entry .onboarding-wrap','grid-column:1/-1'])if(!css.includes(marker))fail(`full-width onboarding/playground layout missing ${marker}`);
for(const marker of ['historyReadyRef','pushAppHistory','popstate','screen==="my-networks"','screen==="playground"'])if(!app.includes(marker))fail(`browser history integration missing ${marker}`);
if(!product.includes('style={{"--score":completeness} as CSSProperties}'))fail('network health ring is not bound to completeness');
for(const marker of ['.network-health-summary','.health-ring strong'])if(!css.includes(marker))fail(`network health readability styling missing ${marker}`);
if(!my.includes('my-networks-signout')||!my.includes('Sign out'))fail('My Networks account sign-out action missing');
if(!product.includes('{auth&&<button')||!alumni.includes('{auth&&<button'))fail('signed-in vertical topbars must expose sign out consistently');
for(const marker of ['@media(min-width:801px)','.profile-overlay .drawer','max-height:calc(100vh - 48px)','border-radius:24px'])if(!css.includes(marker))fail(`desktop profile dialog treatment missing ${marker}`);
if(!setup.includes('playground-gallery'))fail('Playground gallery missing');
console.log('NX-1 UX hardening gate: PASS — full-width Playground, browser history, readable health, consistent sign-out and elevated profile presentation present.');
