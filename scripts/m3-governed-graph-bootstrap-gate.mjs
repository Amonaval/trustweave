import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const checks=[];const ok=(n,v)=>checks.push([n,!!v]);
const graph=read('core/graph/contracts.ts')+read('core/graph/runtime.ts');
const bootstrap=read('core/bootstrap/contracts.ts')+read('core/bootstrap/runtime.ts');
const templateContracts=read('core/templates/contracts.ts');
const professional=read('templates/professional/definition.ts');
const app=read('components/TemplateNetworkApp.tsx');
const panel=read('components/shared/InstitutionalBootstrapPanel.tsx');
ok('typed graph governance contract',graph.includes('GraphRelationshipProvenance')&&graph.includes('GraphRelationshipRule'));
ok('graph validation is additive',graph.includes('validateGraphRelationship')&&graph.includes('buildGovernedEdge'));
ok('relationship definitions support kind constraints',templateContracts.includes('fromKinds?')&&templateContracts.includes('toKinds?'));
ok('professional relationships declare governance constraints',professional.includes('fromKinds:["person","organization"]')&&professional.includes('inverseLabel:"Mentored by"'));
ok('new relationships carry governance metadata',app.includes('buildGovernedEdge')&&app.includes('saveGovernedRelationship'));
ok('institutional bootstrap runtime exists',bootstrap.includes('institutionalBootstrapStages')&&bootstrap.includes('institutionalBootstrapScore'));
ok('institutional bootstrap is admin-visible',app.includes('InstitutionalBootstrapPanel'));
ok('bootstrap reuses existing join code',panel.includes('joinCode')&&panel.includes('onRegenerate'));
ok('bootstrap includes seed template',panel.includes('network-seed-template.csv'));
ok('bootstrap includes claim/delegate stages',panel.includes('BootstrapClaimTxt')&&panel.includes('BootstrapDelegateTxt'));
ok('M3 UI copy uses i18n tokens',panel.includes('useLanguage')&&['InstitutionalBootstrapTxt','BootstrapDescriptionTxt','DownloadSeedTemplateTxt','CopyLaunchInviteTxt'].every(x=>panel.includes(x)));
for(const [n,p] of checks)console.log(`${p?'PASS':'FAIL'} ${n}`);const failed=checks.filter(x=>!x[1]);console.log(`MISSION-3 source gate: ${checks.length-failed.length}/${checks.length}`);if(failed.length)process.exit(1);
